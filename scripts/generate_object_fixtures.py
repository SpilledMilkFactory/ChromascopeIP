#!/usr/bin/env python3
"""Generate M5.7 deterministic, synthetic object-security BMP/media fixtures.

No real photographs, model weights, network calls, or nonstdlib dependencies.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct


def bmp(width, height, pixel):
    stride = ((width * 3 + 3) // 4) * 4
    rows = bytearray()
    for y in range(height - 1, -1, -1):
        row = bytearray()
        for x in range(width):
            r, g, b = pixel(x, y)
            row.extend((b, g, r))
        row.extend(b'\x00' * (stride - width * 3))
        rows.extend(row)
    size = 54 + len(rows)
    header = b'BM' + struct.pack('<IHHI', size, 0, 0, 54)
    header += struct.pack('<IiiHHIIiiII', 40, width, height, 1, 24, 0, len(rows), 2835, 2835, 0, 0)
    return header + rows


def fixtures():
    def shapes(x, y):
        # Deliberately not a COCO object: purely geometric colored primitives.
        if (x - 22) ** 2 + (y - 23) ** 2 <= 12 ** 2:
            return (230, 40, 35)
        if 39 <= x < 57 and 9 <= y < 35:
            return (40, 190, 75)
        return (20, 30, 45)

    yield 'synthetic_shapes_64x48.bmp', bmp(64, 48, shapes), 'synthetic_positive_geometry'
    yield 'synthetic_blank_64x48.bmp', bmp(64, 48, lambda x, y: (12, 12, 12)), 'synthetic_out_of_vocabulary'
    yield 'truncated_png.bin', b'\x89PNG\r\n\x1a\n\x00\x00', 'malformed_reject'
    # A complete BMP header with a pixel count above the global resource budget.
    oversized = b'BM' + struct.pack('<IHHI', 54, 0, 0, 54)
    oversized += struct.pack('<IiiHHIIiiII', 40, 2_000_000, 2_000_000, 1, 24, 0, 0, 0, 0, 0, 0)
    yield 'oversized_dimensions.bmp', oversized, 'malformed_reject'
    # PNG signature with invalid IHDR length: deterministic rejection before codec.
    yield 'invalid_ihdr.png', b'\x89PNG\r\n\x1a\n' + struct.pack('>I', 12) + b'IHDR' + b'\x00' * 13, 'malformed_reject'


def generate(output):
    output.mkdir(parents=True, exist_ok=True)
    entries = []
    for name, data, role in fixtures():
        (output / name).write_bytes(data)
        entries.append({'file': name, 'role': role,
                        'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()})
    manifest = {
        'schema_version': 1,
        'generator': 'scripts/generate_object_fixtures.py',
        'rights': 'original synthetic bytes generated by this project; no human or third-party media',
        'expected_semantics': 'none; colored geometry is not COCO ground truth',
        'fixtures': entries,
    }
    (output / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    args = parser.parse_args()
    result = generate(args.output_dir)
    print(f"Generated {len(result['fixtures'])} synthetic fixture files in {args.output_dir}")


if __name__ == '__main__':
    main()
